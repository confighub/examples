package argo

import (
	"fmt"
	"strings"
)

// ArgobotVersion is the argobot release argobot.sh installs unless told
// otherwise. It has to be 0.2 or later: those run as a service account and
// listen on a Channel. It also finds a moved estate's Applications by the
// Space their source reads, since they keep Argo's names.
const ArgobotVersion = "v0.2.3"

// ArgobotScript writes argobot.sh, which runs argobot beside Argo CD as the
// service account the Targets grant, on a Channel in the Targets' Space.
// argobot is what records each Application's live status on the Release it
// synced, and what makes a published release land at once.
func ArgobotScript(prefix string) string {
	targets := prefix + "-targets"
	account := deliveryAccount(prefix)
	var L []string
	add := func(f string, a ...any) { L = append(L, fmt.Sprintf(f, a...)) }
	add("#!/usr/bin/env bash")
	add("# Run argobot beside Argo CD. Written by `cub argo apply`. Read it, then run it:")
	add("#")
	add("#   ARGOCD_CONTEXT=<kubectl context of the cluster Argo CD runs on> \\")
	add("#   CONFIGHUB_URL=<ConfigHub's address, as that cluster reaches it> bash argobot.sh")
	add("#")
	add("# argobot connects to ConfigHub as the service account %s, which every", account)
	add("# Target here grants, so it acts for exactly these Targets, and it hears of")
	add("# each published release on the Channel %s/argobot. It does two things:", targets)
	add("#")
	add("# - When a variant's Space publishes a release, it hard-refreshes the")
	add("#   Applications reading that Space. Argo CD caches the digest a tag resolved")
	add("#   to, so without this a release waits for Argo's own poll.")
	add("# - It records each Application's live state (sync, health, operation) on the")
	add("#   Release the Application synced, which the Healthy gate and the ConfigHub")
	add("#   UI read.")
	add("#")
	add("# Both find an Application by the Space its source reads.")
	add("set -euo pipefail")
	add(`ctx=${ARGOCD_CONTEXT:-$(kubectl config current-context 2>/dev/null || true)}`)
	add(`[ -n "$ctx" ] || { echo "no kubectl context: set ARGOCD_CONTEXT to the cluster Argo CD runs on"; exit 1; }`)
	add(`echo "every kubectl call below uses context $ctx"`)
	add(`k() { kubectl --context "$ctx" "$@"; }`)
	L = append(L, credentialHelpers()...)
	add(`url=${CONFIGHUB_URL:-}`)
	add(`[ -n "$url" ] || { echo "set CONFIGHUB_URL to ConfigHub's address as the cluster reaches it, e.g. https://hub.confighub.com"; exit 1; }`)
	add(`version=${ARGOBOT_VERSION:-%s}`, ArgobotVersion)
	add(`case "$version" in v0.1.*) echo "argobot $version cannot run as a service account; use %s or later"; exit 1 ;; esac`, ArgobotVersion)
	add(`ns=${ARGOCD_NAMESPACE:-argocd}`)
	add(`[ "$ns" = argocd ] || echo "note: argobot's manifest grants it a Role in the argocd namespace; give it the same in $ns"`)
	add(`cub auth status >/dev/null 2>&1 || { echo "cub is not signed in to ConfigHub: run 'cub auth login', or 'cub auth login --private-key=<key>' on a server with no identity provider"; exit 1; }`)
	add("")
	add("# argobot records each release's live status on the Release, which takes")
	add("# EditChildren on the Target it was published to, and finds the Targets by")
	add("# View and ViewChildren. apply.sh grants all three on the Targets it creates;")
	add("# this covers any it has not granted yet.")
	add("cub serviceaccount create %s --allow-exists --quiet", account)
	add("# Read the Targets first: a failed list inside the loop's word list would not")
	add("# stop the script, and argobot would be installed without the grant.")
	add(`target_slugs=$(cub target list --space %s -o jq='.[].Target.Slug' | tr -d '"') || { echo "could not list the Targets in %s"; exit 1; }`, targets, targets)
	add(`[ -n "$target_slugs" ] || { echo "%s holds no Targets: run apply.sh first"; exit 1; }`, targets)
	add(`for t in $target_slugs; do`)
	add(`  cub target update "$t" --space %[1]s --permission View:serviceaccount:%[2]s --permission ViewChildren:serviceaccount:%[2]s --permission EditChildren:serviceaccount:%[2]s --quiet`, targets, account)
	add("done")
	add("# Its Channel, subscribed to published releases, which is what")
	add("# `argobot --print-subscriptions` prints. No role includes Claim, so the")
	add("# Channel grants it to the service account.")
	add(`if cub channel get %s/argobot >/dev/null 2>&1; then`, targets)
	add(`  cub channel update %s/argobot --patch --permission Claim:serviceaccount:%s --quiet`, targets, account)
	add("else")
	add(`  echo '[{"EventTypes":["release.published"]}]' | cub channel create argobot --space %s --subscriptions - --permission Claim:serviceaccount:%s --quiet`, targets, account)
	add("fi")
	add("")
	add("# Its Namespace, ServiceAccount, RBAC and Deployment, as argobot publishes them.")
	add(`k apply -f "https://raw.githubusercontent.com/confighub/argobot/$version/manifests/argobot.yaml"`)
	add("# Its credential: a key of the service account. ConfigHub keeps only the")
	add("# public half. A key the Secret already holds is kept while ConfigHub lists")
	add("# it; the Secret records its id. Otherwise a new one is made, and the other")
	add("# keys argobot on this context had are removed once the Secret holds it. The")
	add("# private half is on disk only in a temporary directory, until it is read.")
	add(`key_desc="argobot on $ctx"`)
	add(`held_kid=$(k -n argobot get secret argobot-secrets -o jsonpath='{.metadata.annotations.confighub\.com/key-id}' 2>/dev/null || true)`)
	add(`key=""; kid=""; fresh=0`)
	add(`if [ -n "$held_kid" ] && key_ids %s | grep -xF "$held_kid" >/dev/null; then`, account)
	add(`  key=$(k -n argobot get secret argobot-secrets -o jsonpath='{.data.CONFIGHUB_AUTH_PRIVATE_KEY}' | base64 --decode)`)
	add(`  kid=$held_kid`)
	add(`  echo "argobot's key of %s is still registered: kept"`, account)
	add("fi")
	add(`if [ -z "$key" ]; then`)
	add(`  before=$(key_ids %s) || { echo "could not list the keys of %s"; exit 1; }`, account, account)
	add(`  key_dir=$(mktemp -d)`)
	add(`  trap 'rm -rf "$key_dir"' EXIT`)
	add(`  cub serviceaccount key add %s --generate "$key_dir/argobot.jwk" --description "$key_desc" >/dev/null || { echo "could not add a key for %s"; exit 1; }`, account, account)
	add(`  key=$(cat "$key_dir/argobot.jwk"); rm -rf "$key_dir"`)
	add(`  kid=$(key_ids %s | grep -vxF -f <(printf '%%s\n' "$before") | sed -n 1p) || kid=""`, account)
	add(`  [ -n "$kid" ] || echo "the new key of %s is not listed, so earlier ones are left; the next run replaces it"`, account)
	add(`  fresh=1`)
	add("fi")
	add(`k -n argobot create secret generic argobot-secrets --from-file=CONFIGHUB_AUTH_PRIVATE_KEY=<(printf '%%s' "$key") --dry-run=client -o yaml \`)
	add(`  | k annotate --local -f - confighub.com/key-id="$kid" -o yaml | write_secret argobot argobot-secrets`)
	add(`unset key`)
	add(`if [ -n "$kid" ]; then`)
	add(`  key_ids %[1]s "$key_desc" | { while read -r old; do`, account)
	add(`    [ "$old" != "$kid" ] || continue`)
	add(`    cub serviceaccount key delete %[1]s "$old" >/dev/null && echo "removed an earlier key of %[1]s" || echo "could not remove an earlier key of %[1]s: cub serviceaccount key delete %[1]s $old"`, account)
	add(`  done; } || echo "could not list the keys of %s, so earlier ones are not removed"`, account)
	add("fi")
	add(`k -n argobot set env deployment/argobot CONFIGHUB_URL="$url" CONFIGHUB_CHANNEL=%s/argobot ARGO_NAMESPACE="$ns"`, targets)
	add(`k -n argobot set image deployment/argobot argobot="ghcr.io/confighub/argobot:$version"`)
	add("# argobot reads its key when it starts, so a new one needs a new pod.")
	add(`[ "$fresh" = 0 ] || k -n argobot rollout restart deployment/argobot`)
	add(`k -n argobot rollout status deployment/argobot --timeout=5m`)
	add("")
	add(`echo "argobot $version runs as %s on %s/argobot. What it does:"`, account, targets)
	add(`echo "  kubectl --context $ctx -n argobot logs deploy/argobot"`)
	add(`echo "Whether it holds the Channel:"`)
	add(`echo "  cub channel get %s/argobot"`, targets)
	add(`echo "Each release an Application syncs carries its live status:"`)
	add(`echo "  cub release list --space <variant Space>"`)
	return strings.Join(L, "\n") + "\n"
}
